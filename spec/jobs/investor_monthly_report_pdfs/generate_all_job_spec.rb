# frozen_string_literal: true

require 'rails_helper'

RSpec.describe InvestorMonthlyReportPdfs::GenerateAllJob, type: :job do
  let!(:admin) do
    User.create!(email: 'generate-all-job-admin@test.com', name: 'Admin', role: 'ADMIN', provider: 'google_oauth2', uid: 'generate-all-job-admin')
  end
  let(:run) { InvestorMonthlyReportPdfs::GenerationRun }

  before do
    allow(InvestorMonthlyReportPdfs::Generate).to receive(:call) do |on_progress:, **|
      on_progress.call(processed: 1, total: 2, generated: 1, failed: [])
      on_progress.call(processed: 2, total: 2, generated: 1, failed: ['Tulio'])
      InvestorMonthlyReportPdfs::Generate::Result.new(month: '2026-07', generated: [], skipped: [], failed: [])
    end
  end

  after { described_class.release }

  describe '#perform' do
    it 'calls Generate for the month, saves the progress and marks the run finished' do
      described_class.new.perform(month: '2026-07', generated_by_id: admin.id)

      expect(InvestorMonthlyReportPdfs::Generate).to have_received(:call)
        .with(month: '2026-07', generated_by: admin, on_progress: kind_of(Proc))
      expect(run.as_json_for_admin).to include(
        month: '2026-07', running: false, processed: 2, total: 2, generated: 1, failed: ['Tulio'],
      )
      expect(run.as_json_for_admin[:finishedAt]).to be_present
      expect(described_class.running_here?).to be(false)
    end

    it 'leaves the run unfinished if Generate raises, so the watchdog can resume it' do
      allow(InvestorMonthlyReportPdfs::Generate).to receive(:call).and_raise(StandardError, 'boom')

      expect do
        described_class.new.perform(month: '2026-07', generated_by_id: admin.id)
      end.to raise_error(StandardError, 'boom')

      expect(run.active?).to be(true)
      expect(described_class.running_here?).to be(false)
    end

    it 'does not run while another run is going in this process' do
      described_class.claim

      described_class.new.perform(month: '2026-07', generated_by_id: admin.id)

      expect(InvestorMonthlyReportPdfs::Generate).not_to have_received(:call)
    end

    it 'keeps the PDFs generated by earlier attempts in the count when it resumes' do
      run.start!(month: '2026-07', generated_by_id: admin.id)
      run.progress!(processed: 5, total: 10, generated: 5, failed: [])

      described_class.new.perform(month: '2026-07', generated_by_id: admin.id)

      expect(run.current).to include('attempts' => 2, 'generated' => 6)
    end

    it "gives up after #{InvestorMonthlyReportPdfs::GenerationRun::MAX_ATTEMPTS} attempts" do
      InvestorMonthlyReportPdfs::GenerationRun::MAX_ATTEMPTS.times do
        run.start!(month: '2026-07', generated_by_id: admin.id)
      end

      described_class.new.perform(month: '2026-07', generated_by_id: admin.id)

      expect(InvestorMonthlyReportPdfs::Generate).not_to have_received(:call)
      expect(run.as_json_for_admin).to include(aborted: true, running: false)
    end
  end
end
